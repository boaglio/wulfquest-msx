#!/usr/bin/env python3
"""The palette for the ROM, from wulfquest/data/art/palette.json (AGENTS.md §4).

Until the converter (M1) takes over, this writes build/gen/palette.h: the
game's 16 colours as the nearest V9938 colours, 3 bits a channel, in the
two-byte form VDP_SetPalette takes ([0|red:3|0|blue:3], [0:5|green:3]).

    tools/gen_palette.py PALETTE_JSON OUT_HEADER
"""
import json
import sys


def three_bits(v):
    """0..255 to the nearest of the V9938's 0..7."""
    return (v * 7 + 127) // 255


def main(src, out):
    with open(src, encoding="utf-8") as f:
        entries = sorted(json.load(f)["entries"], key=lambda e: e["i"])
    if [e["i"] for e in entries] != list(range(16)):
        sys.exit(f"gen_palette: {src} must hold entries 0 to 15")
    lines = []
    for e in entries:
        rgb = e["rgb"].lstrip("#")
        r, g, b = (three_bits(int(rgb[k:k + 2], 16)) for k in (0, 2, 4))
        lines.append(f"\t0x{r << 4 | b:02X}, 0x{g:02X},\t// {e['i']:2} {e['name']} #{rgb}")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/gen_palette.py from wulfquest/data/art/palette.json. Do not edit.\n")
        f.write("#pragma once\n\n")
        f.write("static const unsigned char g_Palette[16 * 2] = {\n")
        f.write("\n".join(lines) + "\n};\n")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
