package wulfmsx.convert;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

/** Small helpers for the files the converter writes. */
final class Gen {

    private Gen() {
    }

    static String banner(String from) {
        return "// Generated by convert/ from wulfquest/" + from + ". Do not edit.\n";
    }

    /** A C identifier from a data id: upper case, anything else an underscore. */
    static String cName(String id) {
        return id.toUpperCase(java.util.Locale.ROOT).replaceAll("[^A-Z0-9]", "_");
    }

    static void write(Path file, String text) {
        write(file, text.getBytes(StandardCharsets.UTF_8));
    }

    static void write(Path file, byte[] bytes) {
        try {
            Files.createDirectories(file.getParent());
            Files.write(file, bytes);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }
}
